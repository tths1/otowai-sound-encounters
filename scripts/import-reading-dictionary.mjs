// Reproducible import from MIT-licensed pinyin-data. Kana is NOT supplied by this source.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
const revision='9e5e9bdfe8add694300e0cc93a27b803b68377f9';
const source=`https://raw.githubusercontent.com/mozillazg/pinyin-data/${revision}/`;
const local=process.argv[2];
const inputs={};
for(const name of ['pinyin.txt','kMandarin_8105.txt','kTGHZ2013.txt','kXHC1983.txt','LICENSE']) {
  if(local) inputs[name]=await fs.readFile(path.join(local,name),'utf8');
  else { const response=await fetch(source+name);if(!response.ok)throw Error(`Download failed: ${name}`);inputs[name]=await response.text(); }
}
// Remove tone marks only: ü and ê are distinct letters, not tones.
const normalize=s=>s.trim().toLowerCase().normalize('NFD').replace(/[\u0300\u0301\u0304\u030c]/g,'').normalize('NFC');
function parse(text){
 const result={};
 for(const match of text.matchAll(/^U\+([0-9A-F]+):\s*([^#\n]+)/gm)) {
   const values=[...new Set(match[2].trim().split(',').map(normalize))];
   if(values.some(v=>!v || !/^[a-züê]+$/.test(v)))throw Error(`Invalid reading: ${match[0]}`);
   result[String.fromCodePoint(parseInt(match[1],16))]=values;
 }
 return result;
}
const readings=parse(inputs['pinyin.txt']);
const common=parse(inputs['kMandarin_8105.txt']);
if(Object.keys(common).length!==8105)throw Error('Incomplete common-character source');
for(const [char,values] of Object.entries(common)) readings[char]=[...new Set([...values,...readings[char]||[]])];
// The merged archive includes historical/dialect readings. Do not expose that
// union as everyday choices. Prefer the newer normative dictionary, never union
// older extra readings into it; unresolved rare polyphones require review.
const modern=parse(inputs['kTGHZ2013.txt']);
const older=parse(inputs['kXHC1983.txt']);
if(Object.keys(common).some(char=>!modern[char]))throw Error('Incomplete normative reading source');
const selectable=Object.fromEntries(Object.entries(readings).map(([char,values])=>[
  char,modern[char]||older[char]||(values.length===1?values:[])
]));
const primary=Object.fromEntries(Object.entries(readings).map(([char,values])=>[char,values[0]]));
const meta={source:'https://github.com/mozillazg/pinyin-data',revision,license:'MIT',characterCount:Object.keys(readings).length,commonCount:Object.keys(common).length,readingCount:new Set(Object.values(readings).flat()).size,sha256:Object.fromEntries(Object.entries(inputs).map(([k,v])=>[k,crypto.createHash('sha256').update(v).digest('hex')]))};
const js=`// Generated by scripts/import-reading-dictionary.mjs; see pinyin-data-LICENSE.txt.\nwindow.OTOWAI_DICTIONARY_META = ${JSON.stringify(meta)};\nwindow.OTOWAI_COMMON_CHARACTERS = ${JSON.stringify(Object.keys(common).join(''))};\nwindow.OTOWAI_READINGS_BY_CHAR = ${JSON.stringify(readings)};\nwindow.OTOWAI_SELECTABLE_READINGS_BY_CHAR = ${JSON.stringify(selectable)};\nwindow.OTOWAI_PINYIN_BY_CHAR = ${JSON.stringify(primary)};\n`;
await fs.writeFile(new URL('../static-site/pinyin-data.js',import.meta.url),js);
await fs.writeFile(new URL('../static-site/pinyin-data-LICENSE.txt',import.meta.url),`Source: ${meta.source}\nRevision: ${revision}\nReadings only; kana approximations are this project's review candidates.\n\n${inputs.LICENSE}`);
